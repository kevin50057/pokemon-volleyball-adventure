/** 闖關模式目前語言的文字表。 */
export const T: Texts = pick<Texts>({ zh, en, ko });

/**
 * 韓文助詞：名字最後一個字有收尾音（받침）就用 a（을、이），沒有就用 b（를、가）。
 * 不是韓文字（例如英文、數字）時寫成「을(를)」。只在 ko 的文字表用得到，其他語言回傳空字串。
 */
export function josa(word: string, a: string, b: string): string {
  if (lang() !== 'ko') return '';
  const c = word.charCodeAt(word.length - 1);
  if (c >= 0xAC00 && c <= 0xD7A3) return (c - 0xAC00) % 28 ? a : b;
  return a + '(' + b + ')';
}
/** 英文複數字尾：n 不是 1 就是 's'。只在 en 的文字表用得到。 */
export function plural(n: number): string { return lang() === 'en' && n !== 1 ? 's' : ''; }
